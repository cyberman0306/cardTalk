export interface QuestionCard {
  id: string
  question: string
  followUp: string
}

export type DeckId = 'hello' | 'taste' | 'daily' | 'closer'

export interface Deck {
  id: DeckId
  title: string
  mood: string
  description: string
  cards: QuestionCard[]
}

type Entry = [key: string, question: string, followUp: string]

function cards(deck: DeckId, entries: Entry[]): QuestionCard[] {
  return entries.map(([key, question, followUp]) => ({ id: deck + '-' + key, question, followUp }))
}

